"""Страница рабочего пространства: собирается из трёх файлов рядом, в `web/`.

Раньше всё лежало одним сырым литералом на 2676 строк, и это стоило дороже, чем
казалось. Питон съедал обратные слеши регулярок, редактор не подсвечивал ни CSS, ни JS,
`node --check` запускался только через тест, а `git diff` показывал разницу питоновской
строки вместо разницы скрипта.

Чего разделение **не** чинит: область видимости у скрипта по-прежнему одна на всё.
Одноимённая переменная в двух местах файла остаётся такой же ловушкой, какой была —
2026-09-29 на ней зависала панель после каждого прогона. Настоящие области видимости
дают модули ES, а это отдельный разговор: другой способ отдачи и переделка node-тестов,
которые режут `PAGE` по маркерам.

Собираем при импорте, а не при запросе: файлы лежат в образе и не меняются, а `PAGE`
читают и `webui`, и полтора десятка тестов. Сборки у панели нет и не заводится — страница
отдаётся одним ответом, одним `<style>` и одним `<script>`.

Синтаксис скрипта проверяет `tests/test_page_syntax.py` через `node --check`: опечатка в
JS иначе не видна ни ruff, ни тестам — образ соберётся, endpoint ответит 200, а панели
просто не появятся.
"""

from pathlib import Path

WEB = Path(__file__).parent / "web"


def _read(name: str) -> str:
    """Файл страницы из `web/`. Отсутствие — это сломанная сборка, а не штатный случай:
    падаем на импорте, чтобы бот не поднялся с пустой панелью."""
    return (WEB / name).read_text(encoding="utf-8")


